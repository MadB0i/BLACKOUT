// Deterministic seeded RNG (mulberry32) + string seed hashing.
// Used for CHAOS MODE sequencing and seeded visual jitter so replays reproduce.

export function hashSeed(str: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Deterministic RNG stream scoped to a named purpose. */
export function rngFor(seed: string, purpose: string): () => number {
  return mulberry32(hashSeed(`${seed}::${purpose}`));
}
